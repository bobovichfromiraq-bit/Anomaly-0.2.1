#!/usr/bin/env python3
"""
Генератор 3D-мешей для VFX мода «Zone Anomalies» (.obj, открываются в Blender:
File → Import → Wavefront (.obj)). Мод читает те же .obj напрямую.

Соглашения: единичный размер; воронка/облако растут вдоль +Y от 0 до 1;
UV записаны «как есть» (в Minecraft начало координат V — сверху).
    python tools/build_meshes.py
"""
import math
import os
import random

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "main", "resources",
                   "assets", "anomalies", "models", "vfx")
os.makedirs(OUT, exist_ok=True)


class Mesh:
    def __init__(self, name):
        self.name = name
        self.v, self.vt, self.faces = [], [], []   # faces: list of [(vi, ti), ...]

    def vert(self, x, y, z):
        self.v.append((x, y, z))
        return len(self.v)

    def uv(self, u, v):
        self.vt.append((u, v))
        return len(self.vt)

    def face(self, *corners):
        self.faces.append(list(corners))

    def save(self):
        path = os.path.join(OUT, self.name + ".obj")
        with open(path, "w") as f:
            f.write(f"# Zone Anomalies VFX mesh: {self.name} (generated by tools/build_meshes.py)\n")
            f.write(f"o {self.name}\n")
            for x, y, z in self.v:
                f.write(f"v {x:.5f} {y:.5f} {z:.5f}\n")
            for u, v in self.vt:
                f.write(f"vt {u:.5f} {v:.5f}\n")
            for fc in self.faces:
                f.write("f " + " ".join(f"{vi}/{ti}" for vi, ti in fc) + "\n")
        print(f"{self.name}: {len(self.v)} verts, {len(self.faces)} faces")


def tube(name, rings, segs, radius_fn, u_rep, v_rep, offset_fn=None):
    """Открытая труба вдоль Y (0..1) с переменным радиусом. Квады."""
    m = Mesh(name)
    idx = {}
    for j in range(rings + 1):
        y = j / rings
        for i in range(segs + 1):
            a = math.tau * i / segs
            r = radius_fn(y, a)
            ox, oz = offset_fn(y, a) if offset_fn else (0.0, 0.0)
            vi = m.vert(r * math.cos(a) + ox, y, r * math.sin(a) + oz)
            ti = m.uv(i / segs * u_rep, y * v_rep)
            idx[(i, j)] = (vi, ti)
    for j in range(rings):
        for i in range(segs):
            m.face(idx[(i, j)], idx[(i + 1, j)], idx[(i + 1, j + 1)], idx[(i, j + 1)])
    return m


def funnel():
    """Воронка (Gravi): узкий низ, расширяющийся верх, лёгкая S-образная прецессия."""
    # спиральный рельеф (3 «жгута») делает поверхность объёмной, а не гладким конусом
    return tube("funnel", 28, 56,
                lambda y, a: (0.10 + 0.90 * (y ** 0.85)) * (1.0 + 0.075 * math.sin(3 * a - y * 11.0) + 0.03 * math.sin(7 * a + y * 17.0)),
                2.0, 1.0,
                lambda y, a: (0.09 * math.sin(y * math.pi * 2.2), 0.06 * math.sin(y * math.pi * 1.7 + 1.0)))


def plume():
    """Облако ядовитого пара (Chemical): расплывчатые «лепестки», расширяется кверху."""
    return tube("plume", 8, 18,
                lambda y, a: 0.35 + 0.55 * y + 0.13 * math.sin(3 * a + y * 5.0) * (0.4 + y),
                2.0, 1.5)


def ring():
    """Плоское кольцо (ударная волна/ореол на земле), внутренний радиус 0.6, внешний 1.0."""
    m = Mesh("ring")
    segs, rads = 56, 4
    idx = {}
    for j in range(rads + 1):
        r = 0.6 + 0.4 * j / rads
        for i in range(segs + 1):
            a = math.tau * i / segs
            vi = m.vert(r * math.cos(a), 0.0, r * math.sin(a))
            ti = m.uv(i / segs * 3.0, j / rads)
            idx[(i, j)] = (vi, ti)
    for j in range(rads):
        for i in range(segs):
            m.face(idx[(i, j)], idx[(i + 1, j)], idx[(i + 1, j + 1)], idx[(i, j + 1)])
    return m


def icosphere_tris(subdiv):
    t = (1.0 + math.sqrt(5.0)) / 2.0
    verts = [(-1, t, 0), (1, t, 0), (-1, -t, 0), (1, -t, 0), (0, -1, t), (0, 1, t), (0, -1, -t), (0, 1, -t),
             (t, 0, -1), (t, 0, 1), (-t, 0, -1), (-t, 0, 1)]
    verts = [tuple(c / math.sqrt(x * x + y * y + z * z) for c in (x, y, z)) for x, y, z in verts]
    faces = [(0, 11, 5), (0, 5, 1), (0, 1, 7), (0, 7, 10), (0, 10, 11), (1, 5, 9), (5, 11, 4), (11, 10, 2),
             (10, 7, 6), (7, 1, 8), (3, 9, 4), (3, 4, 2), (3, 2, 6), (3, 6, 8), (3, 8, 9), (4, 9, 5),
             (2, 4, 11), (6, 2, 10), (8, 6, 7), (9, 8, 1)]
    cache = {}

    def mid(a, b):
        key = (min(a, b), max(a, b))
        if key not in cache:
            p = tuple((verts[a][k] + verts[b][k]) / 2 for k in range(3))
            n = math.sqrt(sum(c * c for c in p))
            verts.append(tuple(c / n for c in p))
            cache[key] = len(verts) - 1
        return cache[key]

    for _ in range(subdiv):
        new = []
        for a, b, c in faces:
            ab, bc, ca = mid(a, b), mid(b, c), mid(c, a)
            new += [(a, ab, ca), (b, bc, ab), (c, ca, bc), (ab, bc, ca)]
        faces = new
    return verts, faces


def sphere_uv(p):
    x, y, z = p
    n = math.sqrt(x * x + y * y + z * z)
    return 0.5 + math.atan2(z, x) / math.tau, 0.5 - math.asin(max(-1, min(1, y / n))) / math.pi


def sphere(name, subdiv, displace=None, scale=(1, 1, 1)):
    verts, faces = icosphere_tris(subdiv)
    if displace:
        verts = displace(verts)
    m = Mesh(name)
    vids = [m.vert(x * scale[0], y * scale[1], z * scale[2]) for x, y, z in verts]
    for a, b, c in faces:
        us = [sphere_uv(verts[i]) for i in (a, b, c)]
        if max(u for u, _ in us) - min(u for u, _ in us) > 0.5:   # шов: переносим
            us = [(u + 1.0 if u < 0.5 else u, v) for u, v in us]
        m.face(*[(vids[i], m.uv(*us[k])) for k, i in enumerate((a, b, c))])
    return m


def rock(name, seed):
    rnd = random.Random(seed)
    memo = {}

    def displace(vs):
        out = []
        for p in vs:
            key = tuple(round(c, 4) for c in p)
            if key not in memo:
                memo[key] = 0.72 + rnd.random() * 0.5
            out.append(tuple(c * memo[key] for c in p))
        return out
    return sphere(name, 1, displace, (1.0, 0.7 + 0.2 * rnd.random(), 0.85 + 0.2 * rnd.random()))


if __name__ == "__main__":
    for mesh in (funnel(), plume(), ring(), sphere("sphere", 2), sphere("orb", 3), rock("rock_a", 1), rock("rock_b", 2), rock("rock_c", 3)):
        mesh.save()
